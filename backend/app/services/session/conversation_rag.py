"""Conversation planning before retrieval, followed by grounded selection and ranking."""
import re
from app.repositories.conversation_catalog import ConversationCatalogRepository
from app.services.session.conversation_intent import resolve_intent
from app.services.product.catalog_constraints import sale_unit,same_family,product_colors,color_matches
from app.services.product.retrieval_policy import relevant
from app.services.product.text_search import budget
from app.schemas.text_retrieval import TextSearchRequest
from app.services.session.adapter import AnswerInput,AnswerOutput
from app.services.session.openrouter_adapter import OpenRouterCatalogAdapter
from app.services.session.catalog_answer import display_price


def reference_fields(product):
    attrs=product.get('attributes') or {};_,unit,qty=sale_unit(product)
    ink,body,_=product_colors(product)
    return {'price_source_ref':attrs.get('price_source_ref') or product.get('source_ref'),
            'price_basis':attrs.get('price_tax_basis'),
            'price_verification':attrs.get('price_tax_basis_verification'),
            'selling_unit':unit,'pack_quantity':qty,
            'ink_color':'/'.join(sorted(ink)) or None,'body_color':'/'.join(sorted(body)) or None}


def respond(retrieval,settings,question,history,deadline,adapter=None):
    repo=ConversationCatalogRepository(retrieval);catalog=repo.read()
    plan=resolve_intent(question,history,catalog)
    def policy(message):return [],AnswerOutput(message,(),'catalog_policy')
    if plan.clarification:return policy(plan.clarification)
    limits,clarification=budget(plan.query)
    if clarification:return policy(clarification)
    if plan.order or plan.allowed_ids is not None:
        rows=repo.read(plan,limits)
        rows=[p for p in rows if (plan.variant_only or relevant(p,plan.query))]
        if plan.order:
            if re.search(r'ต่อ(?:แพ็ค|แพ็ก|กล่อง)|แบบ(?:แพ็ค|แพ็ก|กล่อง)',plan.query):
                rows=[p for p in rows if sale_unit(p)[0]=='pack']
            elif re.search(r'ต่อ(?:ด้าม|เล่ม|ชิ้น|แท่ง|ก้อน)',plan.query):
                rows=[p for p in rows if sale_unit(p)[0]=='single' and sale_unit(p)[2]==1]
            unit_groups={('pack',sale_unit(p)[2]) if sale_unit(p)[0]=='pack' else (sale_unit(p)[0],None) for p in rows}
            if ('single',None) in unit_groups:
                excluded=sum(sale_unit(p)[0]!='single' for p in rows)
                rows=[p for p in rows if sale_unit(p)[0]=='single']
                plan.note+='\nเรียงราคาต่อรายการเดี่ยวใน catalog ไม่แปลงเป็นราคาต่อชิ้น'
                if excluded:plan.note+='; ไม่รวมแพ็คหรือรายการที่หน่วยยังไม่ชัด '+str(excluded)+' รายการ'
            elif len(unit_groups)>1 or ('ambiguous',None) in unit_groups or ('pack',None) in unit_groups:
                return policy('ข้อมูลหน่วยขายเปรียบเทียบกันไม่ได้ กรุณาระบุว่าจะเทียบต่อด้ามหรือต่อแพ็คกี่ชิ้น')
        products=rows[:plan.limit]
    else:
        result=retrieval.search(TextSearchRequest(query=plan.query,limit=plan.limit),requires_price=plan.requires_price)
        if result.guardrail_status!='allowed':return policy(result.clarification or 'ยังไม่พบสินค้าที่ตรงกับเงื่อนไขใน catalog')
        products=[dict(hit.catalog_snapshot) for hit in result.items]
        if plan.requires_price:products=[p for p in products if p.get('price') is not None and p.get('currency')=='THB']
    if not products:
        return policy('ยังไม่พบสินค้าที่ตรงกับคำถามในข้อมูล catalog ที่มีราคาพร้อมใช้ กรุณาปรับงบหรือระบุเงื่อนไขเพิ่มเติม' if plan.requires_price else 'ยังไม่พบสินค้าที่ตรงกับเงื่อนไขใน catalog')
    if not plan.requires_price and re.search(r'สต็อก|พร้อมส่ง|มีของ',question):
        plan.note+='\nระบบมีเฉพาะสถานะ snapshot ใน catalog ไม่สามารถยืนยันสต็อกสดหรือของพร้อมส่งได้'
    for p in products:
        p.update(reference_fields(p))
        p['variants']=[]
        if plan.variants:
            for variant in catalog:
                if variant['id']==p['id'] or not same_family(p,variant):continue
                ink,body,generic=product_colors(variant);old_ink,old_body,old_generic=product_colors(p)
                if not (ink-old_ink or body-old_body or generic-old_generic):continue
                if plan.variant_color and plan.variant_color not in ink|body|generic:continue
                if plan.requires_price and (variant.get('price') is None or variant.get('currency')!='THB'):continue
                p['variants'].append({**variant,**reference_fields(variant)})
                if len(p['variants'])==5:break
    answer=(adapter or OpenRouterCatalogAdapter(settings,deadline=deadline)).answer(AnswerInput(
        plan.query,history,tuple(products),require_all=bool(plan.order or plan.allowed_ids),note=plan.note))
    # Ranking never depends on the order or price generated by a model.
    prefix=[]
    if plan.order:
        prefix.append('เรียงจาก'+('ราคาน้อยไปมาก' if plan.order=='asc' else 'ราคามากไปน้อย')+'ให้แล้วครับ')
        if len(products)<plan.limit:prefix.append('พบเพียง '+str(len(products))+' รายการที่เข้าเงื่อนไข จากที่ขอ '+str(plan.limit)+' รายการ')
        if 'ไม่รวมแพ็ค' in plan.note:prefix.append('ชุดนี้แยกราคาแบบแพ็คออก เพื่อให้เทียบกันง่ายครับ')
    if 'เฉพาะรายการจากคำตอบล่าสุด' in plan.note:prefix.append('จากตัวเลือกที่คุยกันเมื่อกี้ครับ')
    suffix=[]
    if plan.variants:
        selected=set(answer.product_ids)
        for p in products:
            if p['id'] not in selected:continue
            if not p['variants']:suffix.append('รุ่นนี้ยังไม่พบข้อมูล'+('สี'+plan.variant_color if plan.variant_color else 'สีอื่น')+'ครับ')
            else:
                suffix.append('รุ่นนี้มี'+('สี'+plan.variant_color if plan.variant_color else 'สีอื่นให้เลือกด้วย')+'ครับ')
                for v in p['variants']:suffix.append('• '+v['name']+' — '+display_price(v))
    body=[] if plan.variant_only else [answer.content]
    if re.search(r'สต็อก|พร้อมส่ง|มีของ',question):suffix.append('ส่วนของพร้อมส่ง ยังยืนยันให้ไม่ได้ครับ')
    return products,AnswerOutput('\n'.join(prefix+body+suffix),answer.product_ids,answer.model_name)
